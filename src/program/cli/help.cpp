#include "help.hpp"

#include "basalt/log.hpp"
#include "basalt/program/options.hpp"

namespace basalt::program::cli {

void usage() {
    basalt::log::raw("granite serve --config FILE [--python PY] [server args...]\n"
                 "granite serve MODEL.basalt [--python PY] [server args...]\n"
                 "    runs the Python server (serve/) over this binary: the server reads its options and the engine flags\n"
                 "    from the config file and the command line (the model is the config's or MODEL.basalt, which stands\n"
                 "    for --model); --python defaults to .venv/bin/python in the source tree, else python3; the other\n"
                 "    arguments go to the server.  It runs in the source tree; --model and --config paths are made absolute.\n"
                 "granite generate --model FILE.basalt --tokens \"1,2,3\" [options]\n"
                 "\n"
                 "  --model FILE         the .basalt model file (required): the weights, the drafter, the tokenizer and\n"
                 "                       the vision projector all come from it; the expert profile from\n"
                 "                       --expert-profile, else data/profiles\n"
                 "  --expert-profile P   the expert profile to place at start (the format of data/profiles)\n"
                 "                       instead of the engine's own for the model\n"
                 "  --tokens LIST        the prompt as comma-separated token IDS (required)\n"
                 "  --tokens-file PATH   pretokenized prompt, commas or whitespace (alternative to --tokens)\n"
                 "  --kv fp16|fp8        the attention caches' storage (default fp16; fp8 halves them)\n"
                 "  --serve              stay resident and take requests on stdin (the server's mode)\n"
                 "  --gpu A,B,..|auto    the GPUs to use, as nvidia-smi numbers them (within CUDA_VISIBLE_DEVICES when\n"
                 "                       set): exactly these, the first the main card; a second card runs tensor\n"
                 "                       parallel.  auto = every sm_86 card, the fastest as main.  Default: GPU 0 alone\n"
                 "  --gpu-plan           print the --gpu choice as one JSON line and exit (no model needed)\n"
                 "  --stop-eos           stop when the model emits an end-of-turn token\n"
                 "  --eos-ids LIST       the end-of-turn token ids for --stop-eos (default the pack's); implies it\n"
                 "  --prompt-cache-root N  --serve: checkpoint a prompt's first turn boundary when it is at least N tokens\n"
                 "                       long (default 2048, 0 = never)\n"
                 "  --max-new N          tokens to generate (default 16)\n"
                 "  --max-context N      KV/state capacity (default %lld)\n"
                 "  --vision             --serve takes images, encoded in this process (it reads the model file's\n"
                 "                       vision/mmproj in place): ENC requests borrow the encoder's region from the\n"
                 "                       experts and give it back\n"
                 "  --vision-external    --serve takes images whose embeddings come from granite-vision --model FILE\n"
                 "                       (GENI requests)\n"
                 "  --prompt-cache N     --serve: keep N conversation checkpoints between requests (default 6;\n"
                 "                       0 = read every prompt from the start)\n"
                 "  --conversation-cache-mib N  --serve: RAM budget for parked conversations (default 0 = off)\n"
                 "  --conversation-cache-slots N  --serve: at most N parked conversations (default 4)\n"
                 "  --conversation-cache-min-free-mib N  --serve: physical RAM floor when parking (default 2560)\n"
                 "  --ram-reserve-mib N  RAM left free for the rest of the system (default 2048); the --serve RAM guard\n"
                 "                       holds it (0 = keep nothing, guard off)\n"
                 "  --conversation-cache-min-tokens N  --serve: park only conversations of at least N tokens (default 0 = park every one)\n"
                 "  --conversation-cache-disk-mib N  --serve: park conversations on disk, at most N MiB, and read them back\n"
                 "                       when a prompt starts with one, also after a restart (default 0 = off)\n"
                 "  --conversation-cache-dir DIR  --serve: the disk tier's folder (required with a budget unless the\n"
                 "                       server starts the engine, which uses the model cache folder)\n"
                 "  --batch N / --slots N  --serve (opt-in): up to N requests decode together in batch slots (2..8),\n"
                 "                       each slot with its own session (VRAM like the main one)\n"
                 "  --turn-token ID      --serve: the token that opens a chat turn (default the pack's)\n"
                 "  --tail-role-token ID --serve: a turn of this role right before the last turn is left out of\n"
                 "                       the conversation checkpoint (a trailing effort turn; default -1 = off)\n"
                 "  --spec N             speculative decoding: verify windows of at most N tokens (the last accepted\n"
                 "                       token plus up to N-1 drafts, sized per window by the drafts' joint chance\n"
                 "                       of acceptance against a threshold adapted per request); 0 or 1 = no\n"
                 "                       speculation (default: the pack's drafter decides, 8 with a DSpark drafter;\n"
                 "                       0 without a drafter)\n"
                 "  --grammar on|off     --serve: enforce a request's \"grammar\" (tool-call, JSON-schema or JSON-object\n"
                 "                       grammar) on the sampled tokens; the vocabulary comes from the pack.  Default off\n"
                 "  --draft-log FILE     one line per decode window for draft-policy study\n"
                 "  --ppl-base FILE      llama.cpp KL-divergence base for ppl= requests\n"
                 "  --ppl-out FILE       where ppl= requests write their per-row lines\n"
                 "  --expert-cache N|auto  one card: keep N experts on the card and the least routed in RAM (a\n"
                 "                       diagnostic).  auto (the default) = every expert that fits beside the context\n"
                 "  --vram-reserve-mib N  --serve: the VRAM a lend request without a figure keeps free\n"
                 "                       (POST /v1/vram {\"reserve_mib\": null}; default 0)\n"
                 "  --pool-workers N     CPU expert pool worker count.  Auto when not set: every physical core\n"
                 "                       except the one the host loop spins on (on a hybrid CPU, with --pool-affinity\n"
                 "                       auto: P-cores minus 1 plus half the E-cores; p-cores: P-cores minus 1),\n"
                 "                       lowered so the workers and the host thread fit a cgroup CPU quota\n"
                 "                       (container CPU limit).\n"
                 "  --pool-affinity MODE Which cores size the worker pool (workers are not pinned): all (one\n"
                 "                       worker per physical core), auto (hybrid CPUs: the P-cores minus the\n"
                 "                       host's, plus half the E-cores) or p-cores (the P-cores minus the host's).\n"
                 "                       Auto when not set.\n", (long long) basalt::program::kDefaultContext);
}

}  // namespace basalt::program::cli
